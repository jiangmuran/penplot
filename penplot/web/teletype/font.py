# unknown / non-ASCII character: a small hollow box
FALLBACK = [[(0.6, 1.0), (3.4, 1.0), (3.4, 6.0), (0.6, 6.0), (0.6, 1.0)]]


def _parse(src):
    glyphs = {' ': []}
    for line in src.strip('\n').split('\n'):
        if not line.strip():
            continue
        ch, body = line[0], line[1:]
        strokes = []
        for part in body.split('|'):
            pts = [tuple(float(v) for v in p.split(',')) for p in part.split()]
            if pts:
                strokes.append(pts)
        glyphs[ch] = strokes
    return glyphs


GLYPHS = _parse(_SRC)


def glyph(ch):
    """Strokes for one character (list of point lists, grid units)."""
    g = GLYPHS.get(ch)
    return FALLBACK if g is None else g


def as_json():
    return {'glyphs': {k: v for k, v in GLYPHS.items()}, 'fallback': FALLBACK}


if __name__ == '__main__':
    missing = [chr(c) for c in range(32, 127) if chr(c) not in GLYPHS]
    lifts = sum(len(v) for k, v in GLYPHS.items() if k != ' ')
    print('glyphs: %d  missing: %r  strokes/char: %.2f'
          % (len(GLYPHS), missing, lifts / (len(GLYPHS) - 1)))

#!/usr/bin/env python3
"""Rebuild the bundled open single-line fonts (fonts/open-*.psf).

Every output is a Modified Version of an SIL OFL 1.1 font and is itself
licensed under the OFL 1.1. None of the outputs uses a Reserved Font Name of
its source (see fonts/README.md); the source and its copyright are recorded in
the comment block at the top of each .psf.

Usage (from the repository root, with the [ttf] extra installed):

    python fonts/tools/build_open_fonts.py --src-dir DIR [--only ID ...]

DIR must contain the upstream files listed in SOURCES (download links are in
fonts/README.md). Noto CJK is read from the system path if it is not in DIR.
"""
import argparse
import hashlib
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.dirname(HERE)
sys.path.insert(0, os.path.dirname(FONTS))

from penplot.ttffont import convert_ttf, default_charset  # noqa: E402

NOTO = '/usr/share/fonts/opentype/noto'

# id, output name (display), source file, ttc face, charset, copyright lines, license file
SOURCES = [
    dict(id='open-wenkai-stroke', name='文楷单线 WenKai Stroke',
         src='LXGWWenKai-Regular.ttf', face=0, cjk=True,
         upstream='LXGW WenKai v1.530 (https://github.com/lxgw/LxgwWenKai)',
         copyright=['Copyright 2021-2026 LXGW (https://github.com/lxgw/LxgwWenKai), with Reserved Font Name',
                    "'霞鹜', '霞鶩', '落霞孤鹜', '落霞孤鶩' and 'LXGW'.",
                    'Copyright 2020 The Klee Project Authors (https://github.com/fontworks-fonts/Klee)'],
         license='OFL-LXGW-WenKai.txt'),
    dict(id='open-hei-stroke', name='黑体单线 Hei Stroke',
         src='NotoSansCJK-Regular.ttc', face=2, cjk=True,
         upstream='Noto Sans CJK SC 2.004 (https://github.com/notofonts/noto-cjk)',
         copyright=['Copyright 2014-2021 Adobe (http://www.adobe.com/).',
                    'Noto is a trademark of Google Inc.'],
         license='OFL-Noto-CJK.txt'),
    dict(id='open-caveat-stroke', name='Cursive Stroke',
         src='Caveat[wght].ttf', alt='Caveat.ttf', face=0, cjk=False,
         upstream='Caveat (https://github.com/googlefonts/caveat), default instance wght=400',
         copyright=['Copyright 2014 The Caveat Project Authors (https://github.com/googlefonts/caveat)'],
         license='OFL-Caveat.txt'),
]


def find_src(d, s):
    for name in (s['src'], s.get('alt')):
        if not name:
            continue
        for base in (d, NOTO):
            p = os.path.join(base, name)
            if base and os.path.exists(p):
                return p
    raise SystemExit('missing source %s for %s (see fonts/README.md)' % (s['src'], s['id']))


EXTRA_PUNCT = '—–‘’“”…·•～€￥'


def charset(cjk):
    if cjk:   # ASCII + GB2312 symbol rows (full-width punctuation) + hanzi level 1 + 2
        cs = default_charset(level2=True, latin=True)
        # punctuation that GB2312 text in Unicode commonly uses but the GB2312 table maps elsewhere
        return cs + [c for c in EXTRA_PUNCT if c not in cs]
    return [chr(c) for c in range(0x20, 0x7F)] + list('—–‘’“”…·•€°×')


def build(s, src_dir):
    src = find_src(src_dir, s)
    out = os.path.join(FONTS, s['id'] + '.psf')
    sha = hashlib.sha256(open(src, 'rb').read()).hexdigest()
    t0 = time.time()
    sf = convert_ttf(src, out, chars=charset(s['cjk']), mode='skeleton', size_px=160,
                     face_index=s['face'], name=s['name'])
    # family = our own name too: the source's family is a (possibly reserved) font name
    body = open(out, encoding='utf-8').read().split('\n')
    assert body[0] == '#psf 1'
    head = ['#psf 1',
            '# %s - single-line (skeleton) font generated by penplot' % s['name'],
            '# Source: %s' % s['upstream'],
            '# Source sha256: %s' % sha]
    head += ['# ' + c for c in s['copyright']]
    head += ['# Modifications: centre-line extraction to single strokes, subset to %s.'
             % ('ASCII + GB2312 (symbols, hanzi level 1+2)' if s['cjk'] else 'ASCII + common punctuation'),
             '# This Font Software is licensed under the SIL Open Font License, Version 1.1.',
             '# License text: fonts/LICENSES/%s (https://openfontlicense.org)' % s['license'],
             '# It does not use the Reserved Font Names of its source.']
    rest = [ln for ln in body[1:] if not ln.startswith('family ') and not ln.startswith('author ')]
    i = next(k for k, ln in enumerate(rest) if ln.startswith('name '))
    rest[i + 1:i + 1] = ['family %s' % s['id'], 'author penplot ttf-skeleton (OFL-1.1)']
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(head + rest))
    print('%-20s %5d glyphs, %d missing, %.1f MB, %.0f s' % (
        s['id'], len(sf.glyphs), len(sf.missing), os.path.getsize(out) / 1e6, time.time() - t0))
    if sf.missing:
        print('   missing:', ''.join(sf.missing[:80]))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--src-dir', default='.')
    ap.add_argument('--only', nargs='*')
    a = ap.parse_args()
    for s in SOURCES:
        if not a.only or s['id'] in a.only:
            build(s, a.src_dir)


if __name__ == '__main__':
    main()
